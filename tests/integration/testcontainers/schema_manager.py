# ── Helpers ──────────────────────────────────────────────────────────────


def _qualified_name(table: TableDef) -> str:
    """Return schema-qualified table name: "schema"."table"."""
    return f'"{table.schema_name}"."{table.name}"'


# ── DDL Generation ───────────────────────────────────────────────────────


def _col_ddl(col: ColumnDef, engine: Engine) -> str:
    """Generate column DDL fragment for the given engine."""
    dtype = col.db2_type if engine == Engine.DB2 else col.pg_type
    parts = [f'"{col.name}" {dtype}']

    if not col.nullable:
        parts.append("NOT NULL")

    if col.is_identity:
        if engine == Engine.DB2:
            parts.append("GENERATED BY DEFAULT AS IDENTITY")
        else:
            parts.append("GENERATED BY DEFAULT AS IDENTITY")

    return " ".join(parts)


def generate_create_schema(schema_name: str, engine: Engine) -> str:
    """Generate CREATE SCHEMA DDL (idempotent).

    PostgreSQL: CREATE SCHEMA IF NOT EXISTS "schema";
    Db2:        CREATE SCHEMA "SCHEMA" (uppercase, ignore SQLSTATE 42710).
    """
    if engine == Engine.POSTGRES:
        return f'CREATE SCHEMA IF NOT EXISTS "{schema_name}";'
    else:
        # Db2 schemas are uppercase
        upper_schema = schema_name.upper()
        return (
            f"BEGIN\n"
            f"  DECLARE CONTINUE HANDLER FOR SQLSTATE '42710'\n"
            f"    BEGIN END;\n"
            f"  EXECUTE IMMEDIATE 'CREATE SCHEMA \"{upper_schema}\"';\n"
            f"END"
        )


def generate_create_table(table: TableDef, engine: Engine) -> str:
    """Generate CREATE TABLE IF NOT EXISTS DDL with schema-qualified name.

    Db2 does not natively support IF NOT EXISTS on CREATE TABLE,
    so we wrap it in a BEGIN ATOMIC block that catches -601 (table exists).
    PostgreSQL supports IF NOT EXISTS directly.
    """
    col_lines = [_col_ddl(c, engine) for c in table.columns]

    pk_cols = ", ".join(f'"{c}"' for c in table.primary_key)
    col_lines.append(f"PRIMARY KEY ({pk_cols})")

    columns_sql = ",\n    ".join(col_lines)

    if engine == Engine.POSTGRES:
        qname = _qualified_name(table)
        return (
            f"CREATE TABLE IF NOT EXISTS {qname} (\n"
            f"    {columns_sql}\n"
            f");"
        )
    else:
        # Db2: schema names are uppercase
        db2_qname = f'"{table.schema_name.upper()}"."{table.name}"'
        inner_ddl = (
            f"CREATE TABLE {db2_qname} (\n"
            f"    {columns_sql}\n"
            f")"
        )
        return (
            f"BEGIN\n"
            f"  DECLARE CONTINUE HANDLER FOR SQLSTATE '42710'\n"
            f"    BEGIN END;\n"
            f"  EXECUTE IMMEDIATE '{inner_ddl.replace(chr(39), chr(39)+chr(39))}';\n"
            f"END"
        )


def generate_all_ddl(engine: Engine) -> list[str]:
    """Return ordered CREATE TABLE statements for all tables."""
    # Collect distinct schemas and generate CREATE SCHEMA first
    schemas_seen: set[str] = set()
    stmts: list[str] = []
    for t in TABLES:
        if t.schema_name not in schemas_seen:
            stmts.append(generate_create_schema(t.schema_name, engine))
            schemas_seen.add(t.schema_name)
    stmts.extend(generate_create_table(t, engine) for t in TABLES)
    return stmts


# ── Data insertion ───────────────────────────────────────────────────────

BATCH_SIZE = 100


def _build_insert_sql(table: TableDef, engine: Engine) -> str:
    """Build a parameterised INSERT statement with schema-qualified name."""
    col_names = ", ".join(f'"{c.name}"' for c in table.columns)

    if engine == Engine.POSTGRES:
        placeholders = ", ".join(f"%s" for _ in table.columns)
        qname = _qualified_name(table)
    else:
        # ibm_db uses ? placeholders
        placeholders = ", ".join("?" for _ in table.columns)
        qname = f'"{table.schema_name.upper()}"."{table.name}"'

    return f'INSERT INTO {qname} ({col_names}) VALUES ({placeholders})'


def _row_to_tuple(row: dict[str, Any], table: TableDef) -> tuple:
    """Extract column values from a row dict in table column order."""
    return tuple(row.get(c.name, None) for c in table.columns)


def insert_rows_postgres(
    conn: Any,
    table: TableDef,
    rows: list[dict[str, Any]],
) -> int:
    """Insert rows into PostgreSQL using batched executemany.

    If the table has an identity column, we temporarily set it to allow
    explicit values, then reset the sequence afterwards.
    """
    if not rows:
        return 0

    cur = conn.cursor()
    inserted = 0

    try:
        # For identity columns, allow explicit ID insertion
        qname = _qualified_name(table)
        if table.has_identity:
            cur.execute(
                f'ALTER TABLE {qname} '
                f'ALTER COLUMN "{table.primary_key[0]}" DROP IDENTITY'
            )
            conn.commit()

        sql = _build_insert_sql(table, Engine.POSTGRES)
        tuples = [_row_to_tuple(r, table) for r in rows]

        # Batch insert
        for i in range(0, len(tuples), BATCH_SIZE):
            batch = tuples[i : i + BATCH_SIZE]
            cur.executemany(sql, batch)
            conn.commit()
            inserted += len(batch)

        # Re-add identity and reset sequence
        if table.has_identity:
            pk_col = table.primary_key[0]
            cur.execute(
                f'ALTER TABLE {qname} '
                f'ALTER COLUMN "{pk_col}" ADD GENERATED BY DEFAULT AS IDENTITY'
            )
            # Set sequence to max(id) + 1
            cur.execute(
                f'SELECT COALESCE(MAX("{pk_col}"), 0) + 1 FROM {qname}'
            )
            next_val = cur.fetchone()[0]
            # Get the sequence name — pg_get_serial_sequence needs
            # schema-qualified table as a single string argument
            cur.execute(
                f"SELECT pg_get_serial_sequence('{table.schema_name}.{table.name}', '{pk_col}')"
            )
            seq_result = cur.fetchone()
            if seq_result and seq_result[0]:
                cur.execute(
                    f"ALTER SEQUENCE {seq_result[0]} RESTART WITH {next_val}"
                )
            conn.commit()

    except Exception:
        conn.rollback()
        raise
    finally:
        cur.close()

    return inserted


def insert_rows_db2(
    conn: Any,
    table: TableDef,
    rows: list[dict[str, Any]],
) -> int:
    """Insert rows into Db2 using batched ibm_db prepared statements.

    Identity columns require SET IDENTITY_INSERT before explicit values.
    """
    import ibm_db

    if not rows:
        return 0

    inserted = 0

    # Enable identity insert if needed
    if table.has_identity:
        db2_qname = f'"{table.schema_name.upper()}"."{table.name}"'
        try:
            ibm_db.exec_immediate(
                conn,
                f'ALTER TABLE {db2_qname} ALTER COLUMN "{table.primary_key[0]}" '
                f'SET GENERATED BY DEFAULT',
            )
        except Exception:
            pass  # May already be set

    sql = _build_insert_sql(table, Engine.DB2)
    stmt = ibm_db.prepare(conn, sql)

    for i in range(0, len(rows), BATCH_SIZE):
        batch = rows[i : i + BATCH_SIZE]
        for row in batch:
            values = _row_to_tuple(row, table)
            for idx, val in enumerate(values, start=1):
                ibm_db.bind_param(stmt, idx, val)
            ibm_db.execute(stmt)
            inserted += 1

    return inserted


# ── Schema creation ──────────────────────────────────────────────────────


def create_schema_postgres(conn: Any) -> list[str]:
    """Create wealthadapter schema and all tables in PostgreSQL.

    Returns list of created table names.
    """
    cur = conn.cursor()
    created = []

    # Create schema first (idempotent)
    schemas_done: set[str] = set()
    for table in TABLES:
        if table.schema_name not in schemas_done:
            schema_ddl = generate_create_schema(table.schema_name, Engine.POSTGRES)
            logger.info("Creating PG schema: %s", table.schema_name)
            try:
                cur.execute(schema_ddl)
                conn.commit()
            except Exception as exc:
                conn.rollback()
                logger.error("Failed to create PG schema %s: %s", table.schema_name, exc)
            schemas_done.add(table.schema_name)

    for table in TABLES:
        ddl = generate_create_table(table, Engine.POSTGRES)
        logger.info("Creating PG table: %s.%s", table.schema_name, table.name)
        try:
            cur.execute(ddl)
            conn.commit()
            created.append(table.name)
        except Exception as exc:
            conn.rollback()
            logger.error("Failed to create PG table %s: %s", table.name, exc)
    cur.close()
    return created


def create_schema_db2(conn: Any) -> list[str]:
    """Create WEALTHADAPTER schema and all tables in Db2.

    Returns list of created table names.
    """
    import ibm_db

    created = []

    # Create schema first (idempotent)
    schemas_done: set[str] = set()
    for table in TABLES:
        if table.schema_name not in schemas_done:
            upper_schema = table.schema_name.upper()
            logger.info("Creating Db2 schema: %s", upper_schema)
            try:
                ibm_db.exec_immediate(conn, f'CREATE SCHEMA "{upper_schema}"')
            except Exception as exc:
                error_msg = str(exc)
                if "SQL0601N" in error_msg or "42710" in error_msg:
                    logger.info("  Schema %s already exists (idempotent).", upper_schema)
                else:
                    logger.error("Failed to create Db2 schema %s: %s", upper_schema, exc)
            schemas_done.add(table.schema_name)

    for table in TABLES:
        # Use schema-qualified CREATE TABLE for Db2
        db2_qname = f'"{table.schema_name.upper()}"."{table.name}"'
        col_lines = [_col_ddl(c, Engine.DB2) for c in table.columns]
        pk_cols = ", ".join(f'"{c}"' for c in table.primary_key)
        col_lines.append(f"PRIMARY KEY ({pk_cols})")
        columns_sql = ", ".join(col_lines)
        ddl = f'CREATE TABLE {db2_qname} ({columns_sql})'

        logger.info("Creating Db2 table: %s.%s", table.schema_name.upper(), table.name)
        try:
            ibm_db.exec_immediate(conn, ddl)
            created.append(table.name)
        except Exception as exc:
            error_msg = str(exc)
            if "SQL0601N" in error_msg or "42710" in error_msg:
                logger.info("  Table %s already exists (idempotent).", table.name)
                created.append(table.name)
            else:
                logger.error("Failed to create Db2 table %s: %s", table.name, exc)
    return created


# ── Verification ─────────────────────────────────────────────────────────


@dataclass
class VerificationResult:
    """Row count verification result for one table."""

    table_name: str
    source_count: int
    db2_count: int
    pg_count: int
    db2_match: bool
    pg_match: bool


def verify_row_counts_postgres(conn: Any) -> dict[str, int]:
    """Return row counts for all tables in PostgreSQL (schema-qualified)."""
    cur = conn.cursor()
    counts: dict[str, int] = {}
    for table in TABLES:
        try:
            qname = _qualified_name(table)
            cur.execute(f'SELECT COUNT(*) FROM {qname}')
            counts[table.name] = cur.fetchone()[0]
        except Exception:
            conn.rollback()
            counts[table.name] = -1
    cur.close()
    return counts


def verify_row_counts_db2(conn: Any) -> dict[str, int]:
    """Return row counts for all tables in Db2 (schema-qualified)."""
    import ibm_db

    counts: dict[str, int] = {}
    for table in TABLES:
        try:
            db2_qname = f'"{table.schema_name.upper()}"."{table.name}"'
            stmt = ibm_db.exec_immediate(
                conn, f'SELECT COUNT(*) AS cnt FROM {db2_qname}'
            )
            row = ibm_db.fetch_assoc(stmt)
            counts[table.name] = row["CNT"] if row else -1
        except Exception:
            counts[table.name] = -1
    return counts


def verify_all(
    source_counts: dict[str, int],
    db2_counts: dict[str, int],
    pg_counts: dict[str, int],
) -> list[VerificationResult]:
    """Compare source counts against both databases."""
    results = []
    for table in TABLES:
        src = source_counts.get(table.name, 0)
        db2 = db2_counts.get(table.name, -1)
        pg = pg_counts.get(table.name, -1)
        results.append(
            VerificationResult(
                table_name=table.name,
                source_count=src,
                db2_count=db2,
                pg_count=pg,
                db2_match=(db2 == src),
                pg_match=(pg == src),
            )
        )
    return results

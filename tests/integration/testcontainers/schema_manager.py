"""Schema creation and data population for Db2 and PostgreSQL containers.

This module generates DDL for both engines from a shared table definition,
handles type mapping differences, and provides batched insert logic with
verification.

Type mapping notes (Db2 → PostgreSQL):
  ┌─────────────────┬────────────────────┬──────────────────────────────┐
  │ Db2 Type        │ PostgreSQL Type    │ Notes                        │
  ├─────────────────┼────────────────────┼──────────────────────────────┤
  │ BIGINT          │ BIGINT             │ Identical                    │
  │ INTEGER         │ INTEGER            │ Identical                    │
  │ SMALLINT        │ SMALLINT           │ Identical                    │
  │ VARCHAR(n)      │ VARCHAR(n)         │ Identical                    │
  │ CLOB            │ TEXT               │ PG uses TEXT, no length      │
  │ BLOB            │ BYTEA              │ Binary storage differs       │
  │ DECIMAL(p,s)    │ NUMERIC(p,s)       │ Functionally equivalent      │
  │ DATE            │ DATE               │ Identical                    │
  │ TIMESTAMP       │ TIMESTAMP          │ Identical                    │
  │ XML             │ XML                │ PG supports native XML       │
  └─────────────────┴────────────────────┴──────────────────────────────┘
"""


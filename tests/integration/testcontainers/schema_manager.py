class Engine(str, Enum):
    DB2 = "db2"
    POSTGRES = "postgres"


@dataclass
class ColumnDef:
    """Definition of a single column, engine-agnostic."""

    name: str
    db2_type: str
    pg_type: str
    nullable: bool = True
    is_identity: bool = False
    # For identity columns: Db2 uses GENERATED BY DEFAULT AS IDENTITY,
    # PG uses GENERATED BY DEFAULT AS IDENTITY or SERIAL/BIGSERIAL.


@dataclass
class TableDef:
    """Engine-agnostic table definition."""

    name: str
    schema_name: str
    columns: list[ColumnDef]
    primary_key: list[str]  # column names forming the PK
    has_identity: bool = False


